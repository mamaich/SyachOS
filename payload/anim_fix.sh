#!/system/bin/sh
# Обход четырёхсекундных фризов интерфейса.
#
# Всплывающие окна (например, список лаунчера) при плавном изменении размера
# запрашивают буфер нового размера на каждом кадре, очередь непрерывно
# переаллоцируется, и наступает кадр, когда свободного буфера нет ни одного.
# Приложение засыпает в dequeueBuffer, а будит его только таймаут HWUI —
# ровно через 4 секунды. При скачкообразном изменении размера переаллокация
# одна вместо десятков, и попасть в это окно практически невозможно.
#
# Замеры листания лаунчера:
#
#     значение 0     148 с — ноль фризов
#     значение 0.5    33 с — пять фризов
#
# Поэтому сначала ставился ноль. Но у него обнаружился побочный вред: при
# выключенной анимации в некоторых приложениях (сторонние маркетплейсы) не
# виден ход установки apk — полоски прогресса сами по себе анимации, и при
# нулевом масштабе не рисуются.
#
# Отсюда нынешнее значение 0.25: анимация остаётся, но идёт вчетверо быстрее
# обычной. Кадров в ней вдвое меньше, чем при 0.5, окно голодания по буферам
# почти не открывается, а прогресс виден. Проверено листанием лаунчера:
# при 0.5 пять фризов за 33 с, при 0.25 и 0.1 — ни одного.
#
# Значение меняется без пересборки образа:
#
#     setprop persist.rg52.anim_scale 0.1    и перезагрузиться
#
# Подробности в docs/05-ui-freezes.md.
#
# Настройка живёт на разделе данных, поэтому обнуляется при перепрошивке —
# отсюда и необходимость выставлять её при каждой загрузке.
#
# Значение выставляется не один раз, а удерживается две минуты: на первых
# загрузках после прошивки его успевает перебить первоначальная настройка
# системы, и однократной записи не хватало.

SCALE=$(getprop persist.rg52.anim_scale 2>/dev/null)
[ -z "$SCALE" ] && SCALE=0.25

set_it() {
  cur=$(settings get global animator_duration_scale 2>/dev/null)
  [ "$cur" = "$SCALE" ] && return 0
  settings put global animator_duration_scale $SCALE 2>/dev/null || return 1
  log -t anim_fix "animator_duration_scale $cur -> $SCALE"
  return 0
}

# 1. дождаться, пока settings вообще заработает
i=0
while [ $i -lt 30 ]; do
  set_it && break
  sleep 2
  i=$((i + 1))
done

# 2. удерживать значение две минуты
i=0
while [ $i -lt 24 ]; do
  sleep 5
  set_it
  i=$((i + 1))
done

log -t anim_fix "готово, значение=$(settings get global animator_duration_scale)"
